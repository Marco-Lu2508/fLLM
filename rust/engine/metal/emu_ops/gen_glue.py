#!/usr/bin/env python3
"""Generates the dispatch table of the MSL emulator (package p06b): for every kernel of the given .metal files a C++ lambda that calls the kernel
function with its buffers, its parameter struct and its thread attributes, taken from the signature in the MSL source.

usage: gen_glue.py out.inc file.metal ...
Kernels are the plain `kernel void NAME(...)` definitions and the template instantiations `[[host_name("NAME")]] ... decltype(FN<args>) FN<args>;`.
"""
import re
import sys

ATTR = {
    "threadgroup_position_in_grid": "K_TGPOS",
    "thread_position_in_grid": "K_GID",
    "threadgroups_per_grid": "K_TGRID",
    "threads_per_threadgroup": "K_TPG",
    "thread_position_in_threadgroup": "K_TIDV",
    "thread_index_in_threadgroup": "K_TIDX",
    "simdgroup_index_in_threadgroup": "K_SG",
    "thread_index_in_simdgroup": "K_LANE",
    "simdgroups_per_threadgroup": "K_NSG",
    "threads_per_simdgroup": "K_TPSG",
}


def strip_comments(text):
    return re.sub(r"//[^\n]*", "", text)


def balanced(text, start):
    """Content of the parentheses that open at text[start] == '('."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return text[start + 1 : i]
    raise ValueError("unbalanced parentheses")


def split_params(sig):
    parts, depth, cur = [], 0, ""
    for ch in sig:
        if ch in "([<":
            depth += 1
        elif ch in ")]>":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return [p.strip() for p in parts]


def call_args(sig):
    args = []
    for p in split_params(sig):
        buf = re.search(r"\[\[\s*buffer\((\d+)\)\s*\]\]", p)
        if buf:
            n = int(buf.group(1))
            if "&" in p.split("[[")[0]:
                m = re.search(r"constant\s+([A-Za-z_0-9]+)\s*&", p)
                args.append(f"*reinterpret_cast<const {m.group(1)} *>(pp)")
            else:
                args.append(f"emu::BufTag{{{n}, &e}}")
            continue
        attr = re.search(r"\[\[\s*([a-z_]+)\s*\]\]", p)
        if not attr or attr.group(1) not in ATTR:
            raise ValueError(f"unknown parameter: {p}")
        args.append(f"emu::AttrTag{{&a, emu::{ATTR[attr.group(1)]}}}")
    return args


def main():
    out, files = sys.argv[1], sys.argv[2:]
    entries = []
    for f in files:
        text = strip_comments(open(f, encoding="utf-8").read())
        # template instantiations
        for m in re.finditer(r'host_name\("([^"]+)"\)\s*\]\]\s*(?:\[\[\s*kernel\s*\]\]\s*)?decltype\(\s*([A-Za-z_0-9]+)\s*<([^>]*)>\s*\)', text):
            name, fn, targs = m.group(1), m.group(2), m.group(3)
            d = re.search(r"void\s+" + re.escape(fn) + r"\s*\(", text)
            if not d:
                raise ValueError(f"definition of {fn} not found in {f}")
            sig = balanced(text, d.end() - 1)
            entries.append((name, f"{fn}<{targs}>", call_args(sig)))
        # plain kernels
        for m in re.finditer(r"\bkernel\s+void\s+([A-Za-z_0-9]+)\s*\(", text):
            sig = balanced(text, m.end() - 1)
            entries.append((m.group(1), m.group(1), call_args(sig)))
    with open(out, "w", encoding="utf-8") as o:
        o.write("// generated by gen_glue.py - do not edit\n")
        o.write("struct KernelEntry {\n    const char *name;\n    void (*run)(emu::Env &, const unsigned char *, const emu::Attrs &);\n};\n")
        o.write("static const KernelEntry kKernels[] = {\n")
        for name, fn, args in entries:
            o.write(f'    {{"{name}", [](emu::Env &e, const unsigned char *pp, const emu::Attrs &a) {{ (void)pp; (void)e; (void)a; {fn}({", ".join(args)}); }}}},\n')
        o.write("};\n")
    print(f"{len(entries)} kernels")


if __name__ == "__main__":
    main()
