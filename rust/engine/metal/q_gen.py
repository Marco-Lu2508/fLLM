    ("q4_0", "q_fmt_q4_0", "legacy"),
    ("q4_1", "q_fmt_q4_1", "legacy"),
    ("q5_0", "q_fmt_q5_0", "legacy"),
    ("q5_1", "q_fmt_q5_1", "legacy"),
    ("q8_0", "q_fmt_q8_0", "legacy"),
