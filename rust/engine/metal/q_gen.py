#!/usr/bin/env python3
"""Generates the kernel instantiation files q_mv_*.metal, q_mm_*.metal of package p06a.

Why a generator: the backend finds the kernel names of a library by scanning for `[[host_name("...")]]` (macro-generated names are
invisible to it), so every instantiation is spelled out literally. The files are checked in; run `python3 q_gen.py` in this
directory after changing FORMATS (and keep `plan_quantized_linear` in src/backend/metal/weights/plan.rs in sync: its unit test
compares the kernel names with these files).
"""
