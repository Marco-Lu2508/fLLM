mod tests {
    use super::thinking_kwargs;
    use serde_json::json;

    #[test]
    fn think_false_disables_thinking() {
        let kwargs = thinking_kwargs(&json!({"think": false})).expect("kwargs");
        assert_eq!(kwargs["enable_thinking"], json!(false));
    }

    #[test]
    fn think_level_enables_thinking() {
        let kwargs = thinking_kwargs(&json!({"think": "high"})).expect("kwargs");
        assert_eq!(kwargs["enable_thinking"], json!(true));
    }

    #[test]
    fn format_without_think_keeps_legacy_behaviour() {
        let kwargs = thinking_kwargs(&json!({"format": "json"})).expect("kwargs");
        assert_eq!(kwargs["enable_thinking"], json!(false));
        assert!(thinking_kwargs(&json!({"think": "none"})).is_none());
    }
}