//! Remaining Ollama API surface: `POST /api/show`, `GET /api/ps`, `POST /api/pull`,
//! `DELETE /api/delete`, `HEAD /` and the native `POST /api/embed` reply shape.
//!
//! fLLM keeps exactly one model resident, so the model-management endpoints answer with
//! Ollama's `{"error": …}` object and an explicit status instead of pretending to manage a
//! library of models.
use super::*;

/// Ollama reports every failure as `{"error": "message"}`.
pub(in crate::server) fn error(status: StatusCode, message: &str) -> Response {
    (status, Json(json!({"error": message}))).into_response()
}

/// Ollama model names carry an optional `:latest` tag.
fn model_matches(state: &AppState, requested: &str) -> bool {
    requested == state.model_name || requested == format!("{}:latest", state.model_name)
}

fn requested_model(state: &AppState, body: &Value) -> Result<String, (StatusCode, String)> {
    match body.get("model") {
        None => Err((StatusCode::BAD_REQUEST, "model is required".into())),
        Some(Value::String(name)) if model_matches(state, name) => Ok(state.model_name.clone()),
        Some(Value::String(name)) => Err((
            StatusCode::NOT_FOUND,
            format!("model '{name}' not found"),
        )),
        Some(_) => Err((StatusCode::BAD_REQUEST, "model must be a string".into())),
    }
}

fn details(state: &AppState) -> Value {
    json!({
        "parent_model": "",
        "format": "gguf",
        "family": state.model_arch,
        "families": [state.model_arch],
        "parameter_size": "",
        "quantization_level": "",
    })
}

/// What this server can do with the loaded model, in Ollama's vocabulary.
fn capabilities(state: &AppState) -> Vec<&'static str> {
    let mut caps = vec!["completion", "tools", "insert"];
    if state.vision.is_some() {
        caps.push("vision");
    }
    if state.chat_template.contains("hinking") {
        caps.push("thinking");
    }
    caps
}

/// GGUF facts the engine knows; fields it does not track are left out instead of faked.
fn model_info(state: &AppState) -> Value {
    let mut info = Map::new();
    info.insert("general.architecture".into(), json!(state.model_arch));
    info.insert("general.context_length".into(), json!(state.max_context));
    info.insert("general.embedding_length".into(), json!(state.hidden_size));
    if let Some(eos) = state.tokenizer.eos_ids().first() {
        info.insert("tokenizer.ggml.eos_token_id".into(), json!(eos));
    }
    if let Some(bos) = state.tokenizer.bos_ids().first() {
        info.insert("tokenizer.ggml.bos_token_id".into(), json!(bos));
    }
    Value::Object(info)
}

/// Modelfile parameters rendered from the sampling defaults the engine was started with.
fn parameter_lines(state: &AppState) -> String {
    let sampling = &state.sampling_defaults;
    format!(
        "num_ctx {}\nnum_predict -1\nrepeat_last_n {}\ntemperature {}\ntop_k {}\ntop_p {}\nrepeat_penalty {}\n",
        state.max_context,
        sampling.repeat_last_n,
        sampling.temperature,
        sampling.top_k,
        sampling.top_p,
        sampling.repetition_penalty
    )
}

fn modelfile(state: &AppState) -> String {
    let mut out = format!(
        "# Modelfile generated by fLLM\nFROM {}\nTEMPLATE \"\"\"{}\"\"\"\n",
        state.model_name,
        state.chat_template
    );
    for line in parameter_lines(state).lines() {
        let Some((key, value)) = line.split_once(' ') else {
            continue;
        };
        out.push_str(&format!("PARAMETER {key} {value}\n"));
    }
    out
}

/// Rewrites an OpenAI-shaped error response into Ollama's `{"error": "message"}`
/// shape, keeping the status code. Used for auth and admission failures on the
/// Ollama routes, whose clients expect a plain string error.
pub(in crate::server) async fn error_from(response: Response) -> Response {
    let (status, message) = error_message(response).await;
    error(status, &message)
}

/// `POST /api/show`: model metadata plus a regenerable Modelfile.
pub(in crate::server) async fn show(
    State(state): State<Arc<AppState>>,
    headers: HeaderMap,
    Json(body): Json<Value>,
) -> Response {
    let headers = with_bearer(&headers);
    if let Err(response) = authorize(&state, &headers) {
        return response;
    }
    if let Err(failure) = requested_model(&state, &body) {
        return error(failure.0, &failure.1);
    }
    Json(json!({
        "license": "",
        "modelfile": modelfile(&state),
        "parameters": parameter_lines(&state),
        "template": state.chat_template,
        "details": details(&state),
        "model_info": model_info(&state),
        "capabilities": capabilities(&state),
        "modified_at": iso_now(),
    }))
    .into_response()
}

/// `GET /api/ps`: the single resident model.
pub(in crate::server) async fn ps(State(state): State<Arc<AppState>>, headers: HeaderMap) -> Response {
    let headers = with_bearer(&headers);
    if let Err(response) = authorize(&state, &headers) {
        return response;
    }
    let expires_at = chrono::Utc::now()
        .checked_add_signed(chrono::Duration::minutes(5))
        .map(|time| time.to_rfc3339_opts(chrono::SecondsFormat::Millis, true))
        .unwrap_or_else(iso_now);
    Json(json!({"models":[{
        "name": state.model_name,
        "model": state.model_name,
        "size": 0,
        "digest": "",
        "details": details(&state),
        "expires_at": expires_at,
        "size_vram": 0,
    }]}))
    .into_response()
}

/// `POST /api/pull`: downloading a second model would need a second resident runtime.
pub(in crate::server) async fn pull(
    State(state): State<Arc<AppState>>,
    headers: HeaderMap,
    Json(body): Json<Value>,
) -> Response {
    let headers = with_bearer(&headers);
    if let Err(response) = authorize(&state, &headers) {
        return response;
    }
    let name = match requested_model(&state, &body) {
        Ok(name) => name,
        Err(failure) => return error(failure.0, &failure.1),
    };
    error(
        StatusCode::NOT_IMPLEMENTED,
        &format!(
            "pulling '{name}' is not supported: fLLM serves one model per process, start the server with --model {name} instead"
        ),
    )
}

/// `DELETE /api/delete`: the resident model is part of the running process.
pub(in crate::server) async fn delete_model(
    State(state): State<Arc<AppState>>,
    headers: HeaderMap,
    Json(body): Json<Value>,
) -> Response {
    let headers = with_bearer(&headers);
    if let Err(response) = authorize(&state, &headers) {
        return response;
    }
    let name = match requested_model(&state, &body) {
        Ok(name) => name,
        Err(failure) => return error(failure.0, &failure.1),
    };
    error(
        StatusCode::NOT_IMPLEMENTED,
        &format!(
            "deleting '{name}' is not supported: the model is loaded into this process, stop the server to release it"
        ),
    )
}

/// `HEAD /`: liveness probe used by the Ollama CLI.
pub(in crate::server) async fn head_root() -> Response {
    Response::builder()
        .status(StatusCode::OK)
        .header(
            axum::http::header::CONTENT_TYPE,
            "text/plain; charset=utf-8",
        )
        .body(Body::from("Ollama is running"))
        .unwrap_or_else(|_| StatusCode::OK.into_response())
}

/// Ollama accepts one string, a list of strings, or `{text, image, audio}` entries; only text
/// is meaningful for a text encoder, so media entries are rejected with a clear message.
fn embed_input(value: &Value) -> Result<Value, (StatusCode, String)> {
    match value {
        Value::String(_) => Ok(value.clone()),
        Value::Array(items) => {
            let mut inputs = Vec::with_capacity(items.len());
            for item in items {
                match item {
                    Value::String(_) => inputs.push(item.clone()),
                    Value::Object(map) => match map.get("text") {
                        Some(Value::String(text)) => inputs.push(json!(text)),
                        _ => {
                            return Err((
                                StatusCode::BAD_REQUEST,
                                "embedding inputs must be strings or objects with a text field"
                                    .into(),
                            ))
                        }
                    },
                    _ => {
                        return Err((
                            StatusCode::BAD_REQUEST,
                            "embedding inputs must be strings or objects with a text field"
                                .into(),
                        ))
                    }
                }
            }
            Ok(Value::Array(inputs))
        }
        _ => Err((
            StatusCode::BAD_REQUEST,
            "input must be a string or an array of strings".into(),
        )),
    }
}

/// `POST /api/embed` in Ollama's own reply shape: `{"model": …, "embeddings": [[…]]}`.
pub(in crate::server) async fn embed(
    State(state): State<Arc<AppState>>,
    headers: HeaderMap,
    Json(body): Json<Value>,
) -> Response {
    let headers = with_bearer(&headers);
    if let Err(response) = authorize(&state, &headers) {
        return response;
    }
    let Some(input) = body.get("input") else {
        return error(StatusCode::BAD_REQUEST, "input is required");
    };
    let input = match embed_input(input) {
        Ok(input) => input,
        Err(failure) => return error(failure.0, &failure.1),
    };
    let mut inner = Map::new();
    inner.insert("model".into(), json!(state.model_name));
    inner.insert("input".into(), input);
    // Ollama asks for an optional projection size; the engine answers with `dimensions` when it
    // can, and `truncate`/`keep_alive` never change the embeddings of a fixed-size encoder.
    if let Some(dimensions) = body.get("dimensions").and_then(Value::as_u64) {
        inner.insert("dimensions".into(), json!(dimensions));
    }
    let inner = Value::Object(inner);
    match read_json(super::embeddings(State(state.clone()), headers, Json(inner)).await).await {
        Ok(reply) => Json(json!({
            "model": state.model_name,
            "embeddings": reply["embeddings"].clone(),
        }))
        .into_response(),
        Err((status, message)) => error(status, &message),
    }
}

/// Chat-template keyword that turns reasoning on or off, from Ollama's `think` field.
/// `format` keeps its historical meaning of answering without thinking.
pub(in crate::server) fn thinking_kwargs(body: &Value) -> Option<Map<String, Value>> {
    let mut kwargs = Map::new();
    match body.get("think") {
        Some(Value::Bool(enabled)) => {
            kwargs.insert("enable_thinking".into(), json!(enabled));
        }
        Some(Value::String(level)) if !matches!(level.as_str(), "none" | "false" | "") => {
            kwargs.insert("enable_thinking".into(), json!(true));
        }
        // Anything else (null, numbers, objects) leaves the template default untouched.
        _ => {}
    }
    if kwargs.is_empty() && body.get("format").is_some() {
        kwargs.insert("enable_thinking".into(), json!(false));
    }
    (!kwargs.is_empty()).then_some(kwargs)
}

#[cfg(test)]
mod tests {
    use super::thinking_kwargs;
    use serde_json::json;

    #[test]
    fn think_false_disables_thinking() {
        let kwargs = thinking_kwargs(&json!({"think": false})).expect("kwargs");
        assert_eq!(kwargs["enable_thinking"], json!(false));
    }

    #[test]
    fn think_level_enables_thinking() {
        let kwargs = thinking_kwargs(&json!({"think": "high"})).expect("kwargs");
        assert_eq!(kwargs["enable_thinking"], json!(true));
    }

    #[test]
    fn format_without_think_keeps_legacy_behaviour() {
        let kwargs = thinking_kwargs(&json!({"format": "json"})).expect("kwargs");
        assert_eq!(kwargs["enable_thinking"], json!(false));
        assert!(thinking_kwargs(&json!({"think": "none"})).is_none());
    }
}