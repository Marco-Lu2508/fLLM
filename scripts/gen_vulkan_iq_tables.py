#!/usr/bin/env python3
"""Generate the GLSL lookup tables of the Vulkan IQ shaders from the Rust tables.

The source of truth is rust/engine/src/quant_iq_tables.rs (the tables of ggml-common.h that the CPU decoder quant_iq.rs uses). The Vulkan shaders
read the grids from constant arrays in rust/engine/shaders/vulkan/_iq_grid_*.glsl, written by this script:

  IQ2_XXS / IQ2_XS / IQ2_S   the grid entries hold only the magnitudes 8, 25 and 43 in eight bytes: stored as eight 2-bit codes (0, 1, 2) in 16 bits,
                             two entries per 32-bit word (entry 2k in the low half)
  IQ1_S / IQ1_M              the entries hold only -1, 0 and 1 in eight bytes: eight 2-bit codes (value + 1) in 16 bits, two entries per word
  IQ3_XXS / IQ3_S            four magnitude bytes per entry: the entry as it is, one 32-bit word each

usage: gen_vulkan_iq_tables.py            write the files
       gen_vulkan_iq_tables.py --check    exit 1 when a file differs from what the Rust tables generate (CI / docs gate)

The Rust test `vulkan_iq_grids_match_the_rust_tables` (quant_iq.rs) decodes the generated files again and compares every entry.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "rust/engine/src/quant_iq_tables.rs"
OUT = ROOT / "rust/engine/shaders/vulkan"

HEADER = (
    "// Generated by scripts/gen_vulkan_iq_tables.py from rust/engine/src/quant_iq_tables.rs. Do not edit.\n"
    "// Portions Copyright (c) The ggml authors. Licensed under MIT; see upstream LICENSE (llama.cpp ggml-common.h).\n"
)

# (rust table, output file, glsl array, kind)
TABLES = [
    ("IQ2XXS_GRID", "_iq_grid_iq2xxs.glsl", "IQ2XXS_GRID2", "mag2"),
    ("IQ2XS_GRID", "_iq_grid_iq2xs.glsl", "IQ2XS_GRID2", "mag2"),
    ("IQ2S_GRID", "_iq_grid_iq2s.glsl", "IQ2S_GRID2", "mag2"),
    ("IQ3XXS_GRID", "_iq_grid_iq3xxs.glsl", "IQ3XXS_GRID", "raw"),
    ("IQ3S_GRID", "_iq_grid_iq3s.glsl", "IQ3S_GRID", "raw"),
    ("IQ1S_GRID", "_iq_grid_iq1s.glsl", "IQ1S_GRID2", "sign3"),
]

MAG2 = {8: 0, 25: 1, 43: 2}


def parse_tables(text):
    tables = {}
    for m in re.finditer(r"pub\(super\) const (\w+): \[(\w+); (\d+)\] = \[(.*?)\];", text, re.S):
        name, ty, n, body = m.group(1), m.group(2), int(m.group(3)), m.group(4)
        values = [int(v) for v in re.findall(r"-?\d+", body)]
        assert len(values) == n, f"{name}: {len(values)} values, declared {n}"
        tables[name] = (ty, values)
    return tables


def codes16(entry, kind):
    """eight 2-bit codes (byte j of the 64-bit entry in bits 2j) of a grid entry"""
    out = 0
    for j in range(8):
        byte = (entry >> (8 * j)) & 0xFF
        if kind == "mag2":
            code = MAG2[byte]
        else:
            assert byte in (0x00, 0x01, 0xFF), byte
            code = {0xFF: 0, 0x00: 1, 0x01: 2}[byte]
        out |= code << (2 * j)
    return out


def words_of(values, kind):
    if kind == "raw":
        return list(values)
    entries = [codes16(v, kind) for v in values]
    assert len(entries) % 2 == 0
    return [entries[i] | (entries[i + 1] << 16) for i in range(0, len(entries), 2)]


def render(name, words, kind):
    lines = [HEADER.rstrip("\n")]
    what = {
        "mag2": "two entries per word (entry 2k in the low 16 bits); an entry = eight 2-bit codes, code j (bits 2j) = magnitude of value j: 0 -> 8, 1 -> 25, 2 -> 43",
        "sign3": "two entries per word (entry 2k in the low 16 bits); an entry = eight 2-bit codes, code j (bits 2j) = value j + 1 (-1, 0 or 1)",
        "raw": "one entry per word: four magnitude bytes, byte j = value j",
    }[kind]
    lines.append(f"// {what}")
    lines.append(f"const uint {name}[{len(words)}] = uint[{len(words)}](")
    for i in range(0, len(words), 8):
        row = ", ".join(f"0x{w:08x}u" for w in words[i:i + 8])
        lines.append("    " + row + ("," if i + 8 < len(words) else ""))
    lines.append(");")
    return "\n".join(lines) + "\n"


def main():
    tables = parse_tables(SRC.read_text())
    bad = []
    for rust, fname, glsl, kind in TABLES:
        _, values = tables[rust]
        text = render(glsl, words_of(values, kind), kind)
        path = OUT / fname
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != text:
                bad.append(fname)
        else:
            path.write_text(text, newline="\n")
            print(f"wrote {path.relative_to(ROOT)} ({len(text)} bytes)")
    if bad:
        print("out of date: " + ", ".join(bad) + " (run scripts/gen_vulkan_iq_tables.py)")
        sys.exit(1)


if __name__ == "__main__":
    main()
