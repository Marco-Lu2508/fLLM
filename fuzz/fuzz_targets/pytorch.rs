//! The restricted PyTorch (ZIP + pickle) loader must never execute or trust hostile input: errors only.
//! The first input byte chooses the mode: odd, the rest is a whole archive (ZIP parser); even, the rest is the
//! `data.pkl` of a generated archive that also holds two storages (the pickle interpreter, which a random ZIP never reaches).
#![no_main]
use libfuzzer_sys::fuzz_target;

fn crc32(data: &[u8]) -> u32 {
    let mut crc = 0xffff_ffffu32;
    for byte in data {
        crc ^= u32::from(*byte);
        for _ in 0..8 {
            crc = if crc & 1 != 0 { (crc >> 1) ^ 0xedb8_8320 } else { crc >> 1 };
        }
    }
    !crc
}

/// A ZIP archive with stored (uncompressed) members.
fn stored_zip(files: &[(&str, &[u8])]) -> Vec<u8> {
    let mut out = Vec::new();
    let mut directory = Vec::new();
    for (name, data) in files {
        let offset = out.len() as u32;
        let crc = crc32(data);
        out.extend_from_slice(&[0x50, 0x4b, 0x03, 0x04, 20, 0, 0, 0, 0, 0, 0, 0, 0, 0]);
        out.extend_from_slice(&crc.to_le_bytes());
        out.extend_from_slice(&(data.len() as u32).to_le_bytes());
        out.extend_from_slice(&(data.len() as u32).to_le_bytes());
        out.extend_from_slice(&(name.len() as u16).to_le_bytes());
        out.extend_from_slice(&[0, 0]);
        out.extend_from_slice(name.as_bytes());
        out.extend_from_slice(data);
        directory.extend_from_slice(&[0x50, 0x4b, 0x01, 0x02, 20, 0, 20, 0, 0, 0, 0, 0, 0, 0, 0, 0]);
        directory.extend_from_slice(&crc.to_le_bytes());
        directory.extend_from_slice(&(data.len() as u32).to_le_bytes());
        directory.extend_from_slice(&(data.len() as u32).to_le_bytes());
        directory.extend_from_slice(&(name.len() as u16).to_le_bytes());
        directory.extend_from_slice(&[0; 12]);
        directory.extend_from_slice(&offset.to_le_bytes());
        directory.extend_from_slice(name.as_bytes());
    }
    let start = out.len() as u32;
    out.extend_from_slice(&directory);
    out.extend_from_slice(&[0x50, 0x4b, 0x05, 0x06, 0, 0, 0, 0]);
    out.extend_from_slice(&(files.len() as u16).to_le_bytes());
    out.extend_from_slice(&(files.len() as u16).to_le_bytes());
    out.extend_from_slice(&(directory.len() as u32).to_le_bytes());
    out.extend_from_slice(&start.to_le_bytes());
    out.extend_from_slice(&[0, 0]);
    out
}

fuzz_target!(|data: &[u8]| {
    let Some((mode, rest)) = data.split_first() else { return };
    let archive = if mode & 1 == 1 {
        rest.to_vec()
    } else {
        stored_zip(&[
            ("archive/data.pkl", rest),
            ("archive/data/0", &[0u8; 16]),
            ("archive/data/1", &[0u8; 64]),
            ("archive/byteorder", b"little"),
        ])
    };
    let path = std::env::temp_dir().join(format!("fllm-fuzz-{}.pt", std::process::id()));
    if std::fs::write(&path, archive).is_err() {
        return;
    }
    let _ = fllm_checkpoint::inspect_checkpoint(&path);
});
